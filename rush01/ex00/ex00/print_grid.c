#include "main.h"

void	print_grid(int grid[N][N])
{
	int	a;
	int	c;
	int	r;

	r = 0;
	while (r < N)
	{
		c = 0;
		while (c < N)
		{
			a = grid[r][c] + '0';
			write(1, &a, 1);
			if (c != N - 1)
				write(1, " ", 1);
			c++;
		}
		write(1, "\n", 1);
		r++;
	}
}
