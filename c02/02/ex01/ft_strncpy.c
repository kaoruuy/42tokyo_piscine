char	*ft_strncpy(char *dest, char *src, unsigned int n)
{
	unsigned int	i;

	i = 0;
	while (i < n && src[i] != '\0' && n > 0)
	{
		dest[i] = src[i];
		i++;
	}
	while (i < n)
	{
		dest[i] = '\0';
	}
	return (dest);
}

#include <stdio.h>

int	main(void)
{
	char	destination[] = "destination";
	char	source[] = "source";

	printf("%s\n", ft_strncpy(destination, source, 0));
}
